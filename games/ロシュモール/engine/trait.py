def main():
    a = sys.argv[1:]
    if a and a[0] == "表を書く":
        write_tables()
        return
    if a and a[0] in TABLES:
        n = int(a[1]) if len(a) > 1 else 1
        rows = TABLES[a[0]]
        for x in ([random.choice(rows) for _ in range(n)] if a[0] in ("層", "謎の軸") else random.sample(rows, n)):
            print(f"{a[0]}：{x}")
        return
    kind = a[0] if a else "ふつう"
    fields = {"特別": FIELDS_SPECIAL, "端役": FIELDS_BIT}.get(kind, FIELDS_NORMAL)
    print(f"■ {kind}の人物")
    for name, x in roll(fields):
        print(f"  {name}：{x}")
    print("→ それぞれに理由をつけ、町の具体につなぐ。欲から企てを一つ作る（engine/trait.py 企て）")


