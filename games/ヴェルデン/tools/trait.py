TABLES = {"性格": 性格, "好き": 好き, "嫌い": 嫌い, "過去": 過去, "突飛": 突飛,
          "価値観": 価値観, "手段": 手段, "話し方": 話し方, "決め方": 決め方, "目的": 目的}


def pick(t, n=1):
    idx = random.sample(range(len(t)), n)
    return [f"{t[i]}（{i + 1}）" for i in idx]


def lvl():
    r = random.randint(1, 6) + random.randint(1, 6)
    return (0 if r <= 4 else 1 if r <= 7 else 2 if r <= 10 else 3), r


def ugoki():
    a, ar = lvl(); p, pr = lvl()
    return [
        "■ 動き方",
        "価値観：" + " ／ ".join(pick(価値観, 2)) + "（前を主、後ろを従とする）",
        "手段の癖：" + pick(手段)[0],
        "話し方：" + pick(話し方)[0],
        "決め方：" + pick(決め方)[0],
        "目的：" + pick(目的)[0],
        f"能動性：{a}（2d6={ar}）　押しの強さ：{p}（2d6={pr}）",
    ]


def main(a):
    mode = a[0] if a else ""
    if mode == "表を書く":
        DIR.mkdir(parents=True, exist_ok=True)
        for name, t in TABLES.items():
            body = [f"# 特徴表：{name}（{len(t)}行）", "", "tools/trait.py の中の表を書き出したもの。直すときは trait.py を直して `表を書く` をやり直す。", ""]
            body += [f"{i + 1}. {x}" for i, x in enumerate(t)]
            (DIR / f"{name}.md").write_text("\n".join(body) + "\n", encoding="utf-8")
        print("書いた：", DIR); return
    if mode == "表":
        print(pick(TABLES[a[1]])[0]); return
    if mode == "突飛":
        print("突飛：" + pick(突飛)[0]); return
    if mode == "動き":
        print("\n".join(ugoki())); return
    out = ["■ 心のつくり",
           "性格：" + " ／ ".join(pick(性格, 2)),
           "好き：" + " ／ ".join(pick(好き, 2)),
           "嫌い：" + " ／ ".join(pick(嫌い, 2)),
           "過去と事情：" + " ／ ".join(pick(過去, 2))]
    d = random.randint(1, 10)
    if mode == "特別":
        out.append("突飛：" + pick(突飛)[0] + "（特別な人物）")
    elif d == 1:
        out.append(f"突飛：{pick(突飛)[0]}（1d10={d}）")
    else:
        out.append(f"突飛：なし（1d10={d}）")
    out += ugoki()
    print("\n".join(out))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main(sys.argv[1:])
