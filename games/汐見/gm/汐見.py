def persuade(st, bid, t, g, r, v, q, p, who, rng, h=0, text=None, vals=None, mag=1.0, quiet=False):
    B = st["信念"]
    if bid not in B:
        B[bid] = new_belief(bid, text, vals)
    b = B[bid]
    a = adol(st)
    H = st["心"]
    if who == "瀬島":
        cred = H["信用"] * (1 - .25 * a) + .25 * a * H["安心"]
        safe = H["安心"]
        peer = False
    else:
        n = NPCS[who]
        f = st["縁"].get(who, 0)
        peer = n["peer"]
        mult = (.6 + .8 * a) if peer else (1 - .35 * a)
        cred = clip(f * mult * 1.1)
        safe = f
    diff = g - st["道徳"]
    if .3 < diff <= 1.5:
        sf = 1.35
    elif abs(diff) <= .3:
        sf = 1.0
    elif diff > 1.5:
        sf = .45
    else:
        sf = 1 - .3 * (.5 + a)
    vf = value_fit(st, b["値"]) * t
    grip = ROOT_GRIP[b["根"]] * (.5 if b.get("新") else 1)
    opp = (b["s"] * t < 0)
    resist = abs(b["s"]) * grip * 1.6 if opp else 0
    same = .3 if (b["s"] * t > 0) else 0
    react = p * (.3 + .9 * a + .8 * (st["価値"]["自由"] - .4))
    parts = {
        "基": -.5, "信用": 2.0 * (cred - .5), "安心": .8 * (safe - .5), "理由": .45 * r, "受け止め": .4 * v, "問い": .4 * q,
        "段階": 1.6 * math.log(sf), "価値の合い": 1.4 * vf, "好奇": .8 * (st["気質"]["好奇"] - .5),
        "抵抗": -resist, "同じ向き": same, "反発": -react, "言行": -1.2 * h, "怒り": -.9 * st["気分"]["怒り"],
    }
    L = sum(parts.values())
    pa = sig(L)
    pc = sig(-.8 + .9 * p + 1.0 * (1 - a) + .8 * (st["気質"]["敏感"] - .5) + 1.0 * (st["価値"]["しきたり"] - .45))
    pb = sig(-1.6 + 1.0 * p + 1.2 * a + 1.0 * (st["価値"]["自由"] - .4) + .8 * h + .8 * st["気分"]["怒り"])
    u1, u2, u3 = rng.random(), rng.random(), rng.random()
    if q and r >= 1:
        root = "自分"
    elif r >= 1:
        root = "納得"
    elif peer:
        root = "仲間"
    elif p >= 2:
        root = "罪悪感"
    else:
        root = "権威"
    old = b["s"]
    if u1 < pa:
        out = "受け入れた"
        d = .3 * (1 + .4 * q) * (.6 if same else 1) * mag
        if opp:
            d /= (1 + grip * abs(old))   # 深く根を張った逆の考えは、一晩では消えない
        b["s"] = clip(b["s"] + t * d, -1, 1)
        if old == 0 or old * b["s"] < 0 or (not opp and ROOT_GRIP[root] >= ROOT_GRIP[b["根"]]):
            b["根"] = root
            b["元"] = who
        b["口"] = b["s"]
        if .3 < diff <= 1.5 and (r >= 1 or q) and st["道徳"] < moral_cap(st):
            st["道徳"] = r2(min(6, st["道徳"] + .03))
    elif u2 < pc:
        out = "口では従った（心は動かない）"
        if who == "瀬島":
            b["口"] = t * max(abs(b["s"]), .5)
            if p >= 2:
                b["s"] = clip(b["s"] + t * .05, -1, 1)
                if not b["根"]:
                    b["根"] = "罪悪感"
            if bid not in st["隠し事"]:
                st["隠し事"].append(bid)
        elif peer:
            b["s"] = clip(b["s"] + t * .05, -1, 1)
            if not b["根"]:
                b["根"] = "仲間"
    elif u3 < pb:
        out = "反発した"
        b["s"] = clip(b["s"] - t * .15, -1, 1)
        if who == "瀬島":
            H["信用"] = clip(H["信用"] - .015)
    else:
        if r >= 1 or q:
            out = "保留（考えている）"
            st["保留"].append({"信念": bid, "向き": t, "L": r2(L), "問い": q, "人": who})
        else:
            out = "聞き流した"
    if who == "瀬島":
        H["安心"] = clip(H["安心"] + .01 * v - .02 * (p >= 2))
        H["自律"] = clip(H["自律"] + .01 * q - .012 * p)
        if q:
            st["自己"]["探る"] = clip(st["自己"]["探る"] + .005)
    res = dict(信念=bid, 文=b["文"], 向き=t, 相手=who, 段階差=r2(diff), 内訳={k: r2(x) for k, x in parts.items()},
               L=r2(L), 受け入れ=r2(pa), 口だけ=r2(pc), 反発=r2(pb), 出目=[r2(u1), r2(u2), r2(u3)], 結果=out,
               s=f"{r2(old)}→{r2(b['s'])}", 口=r2(b["口"]), 根=b["根"])
    return res


