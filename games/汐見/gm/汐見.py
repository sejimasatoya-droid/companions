def exposure(st):
    """予定から、人ごとの会う量と行き先の重みを出す。平日は2倍"""
    ex, wsl = {}, {}
    for i, s in enumerate(st["予定"]):
        wt = 2 if i == 0 else 1
        wsl[s] = wsl.get(s, 0) + wt
        for n, x in SLOTS[s]["npc"].items():
            ex[n] = ex.get(n, 0) + x * wt
    return ex, wsl


def week(st, rng, log, sim=False):
    H, V, T, M = st["心"], st["価値"], st["気質"], st["気分"]
    a = adol(st)
    age = agef(st["w"])
    # 1 保留が決まる（あとから効く）
    keep = []
    for pd in st["保留"]:
        pr = sig(pd["L"] + .4 + .4 * pd["問い"])
        u = rng.random()
        if u < pr:
            b = st["信念"][pd["信念"]]
            old = b["s"]
            b["s"] = clip(b["s"] + pd["向き"] * .25, -1, 1)
            b["口"] = b["s"]
            b["根"] = "自分" if pd["問い"] else "納得"
            b["元"] = pd["人"]
            log(f"保留：{b['文']} … {r2(pr)} 出目 {r2(u)} → 腑に落ちた（{r2(old)}→{r2(b['s'])}）")
        elif u > .85:
            log(f"保留：{st['信念'][pd['信念']]['文']} … 出目 {r2(u)} → 忘れた")
        else:
            keep.append(pd)
    st["保留"] = keep[-6:]
    # 2 縁と影響
    ex, wsl = exposure(st)
    for n in st["縁"]:
        if n == "瀬島":
            continue
        x = ex.get(n, 0)
        if n in NPCS and age < NPCS[n]["min"]:
            continue
        f = st["縁"][n]
        st["縁"][n] = r2(clip(f + .02 * x * (1 - f) - .004))
    st["縁"]["瀬島"] = r2(clip(.5 * H["安心"] + .5 * H["信用"]))
    for n, x in ex.items():
        if n not in NPCS or age < NPCS[n]["min"] or x <= 0:
            continue
        npc = NPCS[n]
        f = st["縁"][n]
        mult = (.6 + .8 * a) if npc["peer"] else (1 - .35 * a)
        for k, tv in npc["V"].items():
            V[k] = clip(V[k] + .003 * x * f * mult * (tv - V[k]))
        for bid, t in npc["push"]:
            if rng.random() < .06 * x * f:
                res = persuade(st, bid, t, npc["g"], npc["r"], npc["v"], npc["q"], npc["p"], n, rng)
                if res["結果"] in ("受け入れた", "反発した"):
                    log(f"縁：{n}『{res['文']}』{'+' if t > 0 else '-'} → {res['結果']}（{res['受け入れ']}／{res['s']}）")
    # 3 能力と疲れ、家計
    for s, wt in wsl.items():
        for k, g in SLOTS[s]["ab"].items():
            tal = TALENT[k]
            tv = (1 - T["敏感"]) if tal.startswith("-") else T[tal]
            st["能力"][k] = r2(min(100, st["能力"][k] + .15 * g * wt * (.7 + .6 * tv) * (1 - st["能力"][k] / 115) * (1 - .4 * st["疲れ"])))
        st["疲れ"] = clip(st["疲れ"] + SLOTS[s]["疲れ"] * wt)
        st["家計"] = r2(st["家計"] - SLOTS[s]["費"] * wt)
    st["疲れ"] = r2(clip(st["疲れ"] - .03))
    st["家計"] = r2(st["家計"] + .9)   # 衛兵の給金から暮らしを引いた残り
    # 土台は、扱われ方の積み重ね（応え・一貫）が決める「落ち着きどころ」へ少しずつ寄る
    A = st["愛着"]
    home = .15 + .7 * (.55 * A["応え"] + .45 * A["一貫"]) - .3 * (T["敏感"] - .5) - .1 * (.4 - H["世界"]) + .01 * wsl.get("家", 0)
    H["安心"] = clip(H["安心"] + .04 * (home - H["安心"]))
    H["信用"] = clip(H["信用"] + .01 * (.25 + .6 * A["一貫"] - H["信用"]))
    H["自律"] = clip(H["自律"] + .01 * (.45 - H["自律"]))
    if st["疲れ"] > .6:
        M["不安"] += .08
        M["怒り"] += .06
    # 4 気分がおさまる
    for k in MOODS:
        M[k] = r2(clip(M[k] * .55))
    M["寂しさ"] = r2(clip(M["寂しさ"] + .05 * (1 - H["居場所"])))
    # 5 出来事の受け取りが固まる
    for b in st["信念"].values():
        b["新"] = False
    # 6 発達
    cap = moral_cap(st)
    st["道徳"] = r2(st["道徳"] + .004 * max(0, cap - .6 - st["道徳"]))   # 放っておくと、年相応より少し下で止まる
    rule = st.get("きまり", .5)
    st["自制力"] = r2(clip(st["自制力"] + .0012 * (.3 + rule) * (T["自制"] + .3) + .002 * (H["安心"] - .4) - .001 * st["疲れ"]))
    peerbest = max([st["縁"][n] for n in ("ちよ", "辰", "綾") if n in st["縁"]] + [0])
    H["居場所"] = r2(clip(H["居場所"] + .03 * ((.4 * H["安心"] + .35 * peerbest + .25 * max(st["縁"]["イシ"], st["縁"]["慈恵"], st["縁"]["葛葉"])) - H["居場所"])))
    selfneg = sum(w * max(0, st["信念"][k]["s"]) for k, w in SELF_NEG.items() if k in st["信念"])
    H["自己価値"] = r2(clip(H["自己価値"] + .03 * ((H["有能"] + H["安心"]) / 2 + .1 - selfneg - H["自己価値"])))
    H["世界"] = r2(clip(H["世界"] + .002 * (H["安心"] - .3)))
    for b in st["信念"].values():
        for k, w in b["値"].items():
            if k in V:
                V[k] = clip(V[k] + .0015 * b["s"] * w)
    mv = sum(V.values()) / len(V)   # 価値は「何を先に立てるか」なので、全体の高さはならす
    for k in V:
        V[k] = r2(clip(V[k] - .15 * (mv - .5)))
    if age >= 12.5:
        S = st["自己"]
        div = len(set(st.get("最近", []))) / 8
        S["探る"] = r2(clip(S["探る"] + .004 * (div + H["自律"] - .6)))
        strong = [b for b in st["信念"].values() if abs(b["s"]) > .4]
        own = sum(1 for b in strong if b["根"] in ("自分", "納得", "経験"))
        auth = sum(1 for b in strong if b["根"] in ("権威", "罪悪感"))
        S["定める"] = r2(clip(S["定める"] + .004 * min(1, (own - 3) / 4) * (H["自己価値"] - .3) * 2))
        S["定める_権威"] = r2(clip(S["定める_権威"] + .0015 * (auth - 2)))
    st.setdefault("最近", []).extend(st["予定"])
    st["最近"] = st["最近"][-32:]
    # 7 芽の育ち
    for s, wt in wsl.items():
        for f in SLOT_FUTURE.get(s, []):
            st["芽"][f] = r2(clip(st["芽"].get(f, 0) + .002 * wt * max(0, .2 - st["芽"].get(f, 0)) / .2))   # 通うだけで育つのは .2 まで。それより上は出来事で
    for f in list(st["芽"]):
        st["芽"][f] = r2(max(0, st["芽"][f] - .001))
    # 8 力の目覚め
    S = st["秘密"]
    if S["目覚め"] is None:
        S["力"] = r2(S["力"] + .0008 * max(0, age - 11) + .002 * max(M.values()))
        pw = 0.0 if age < 12 else clip((S["力"] - .5) * .02 + .006 * max(0, max(M.values()) - .5))
        u = rng.random()
        if u < pw:
            S["目覚め"] = power_shape(st, rng, log)
            log(f"目覚め：{r2(pw)} 出目 {r2(u)} → {S['目覚め']}")
    # 9 発覚（妖の血）
    risk = .002 + .01 * S["疑い"]
    if "浜" in st["予定"]:
        risk += .006 * (1 - st["自制力"])
    if "銭湯" in st["予定"]:
        risk += .02
    if "学舎" in st["予定"]:
        risk += .004 * (1.5 if (st["w"] % 52) // 13 == 1 else 1)   # 体操・着替え。夏は薄着
    if S["目覚め"]:
        risk += .01 * (1 - st["自制力"])
    u = rng.random()
    S["疑い"] = r2(clip(S["疑い"] * .995))
    if u < risk:
        who = pick_finder(st, rng)
        log(f"発覚：{r2(risk)} 出目 {r2(u)} → 背中を見た者がいる：{who}")
        if who not in S["知る者"]:
            S["知る者"].append(who)
        if who == "黒田":
            S["疑い"] = 1.0
        st["季"]["出来事"].append(f"発覚（{who}）")
    # 10 傷：ゆっくり癒えるが、底（あと）より下にはならない。ときどき疼く
    W = st.setdefault("傷", {})
    for k, wd in W.items():
        wd["強さ"] = r2(max(wd["底"], wd["強さ"] - (.002 + .004 * H["安心"] + .002 * H["居場所"])))
        if rng.random() < .1 * wd["強さ"]:
            M[WOUND_MOOD[k]] = clip(M[WOUND_MOOD[k]] + .3)
    H["世界"] = r2(clip(H["世界"] - .002 * sum(wd["強さ"] for wd in W.values())))
    # 11 対話しきれない出来事
    fate = roll_fate(st, rng, log)
    # 12 暗い分岐
    dark_check(st, rng, log)
    # 13 次の週へ。その週の出来事
    st["w"] += 1
    ev = roll_event(st, rng)
    if fate:
        ev = tuple(ev) + (f"＋対話しきれない出来事：{fate}（{FATES[fate]['text']}）",)
    if st["w"] % 52 == BIRTH % 52:
        birthday(st, rng, log)
    return ev


def add_wound(st, kind, x):
    W = st.setdefault("傷", {})
    wd = W.setdefault(kind, {"強さ": 0.0, "底": 0.0})
    wd["強さ"] = r2(clip(wd["強さ"] + x))
    wd["底"] = r2(clip(max(wd["底"], .35 * wd["強さ"])))


