def future_scores(st):
    V = st["価値"]
    out = {}
    for nm, (vals, ab, cond) in FUTURES.items():
        vf = sum(w * (V[k] - .45) for k, w in vals.items()) / max(1, sum(abs(w) for w in vals.values()))
        mean_ab = sum(st["能力"].values()) / len(ABIL)
        af = (sum(w * st["能力"][k] for k, w in ab.items()) / sum(ab.values()) - mean_ab) / 40 + mean_ab / 200
        ok = True
        if cond == "目覚め":
            ok = st["秘密"]["目覚め"] is not None
        elif cond == "受け入れ":
            ok = st["信念"].get("化け物", {"s": 1})["s"] < 0
        elif cond == "島":
            ok = st["縁"]["イシ"] > .3 or st["信念"].get("島の子", {"s": 0})["s"] > .4
        elif cond and cond.startswith("縁:"):
            ok = st["縁"].get(cond[2:], 0) > .4
        elif cond and cond.startswith("暗:"):
            ok = st["暗"].get(cond[2:], 0) >= 2
        elif cond == "安心":
            ok = st["心"]["安心"] > .55
        if not ok:
            continue
        out[nm] = 2.5 * vf + .8 * af + 5 * st["芽"].get(nm, 0) + .8 * st.get("憧れ", {}).get(nm, 0)
    return out


def ending(st, rng, log):
    sc = future_scores(st)
    names = list(sc)
    i, ps, u = softmax_pick([sc[n] for n in names], rng, temp=.6)
    order = sorted(zip(names, ps), key=lambda x: -x[1])
    log("進路の確率：" + "／".join(f"{n} {r2(p)}" for n, p in order[:8]) + f" 出目 {r2(u)} → {names[i]}")
    H = st["心"]
    rel = "そばにいる" if H["安心"] > .6 and H["信用"] > .55 else "ときどき帰ってくる" if H["安心"] > .4 else "手紙だけ" if H["安心"] > .22 else "縁が切れる"
    if st["暗"]["家出"] == 2:
        rel = "手紙だけ" if H["安心"] > .3 else "縁が切れる"
    top = sorted(st["価値"].items(), key=lambda x: -x[1])[:3]
    log(f"瀬島との関係：{rel}／愛着：{attach_style(st)}／自己：{identity(st)}／道徳：{STAGES[int(st['道徳'])]}（{st['道徳']}）／自制力 {st['自制力']}")
    log("大事にするもの：" + "・".join(f"{k}{r2(v)}" for k, v in top) + f"／力：{st['秘密']['目覚め'] or '目覚めず'}")
    return names[i], rel


