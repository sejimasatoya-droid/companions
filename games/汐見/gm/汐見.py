def roll_fate(st, rng, log):
    age = agef(st["w"])
    u = rng.random()
    if u >= FATE_RATE:
        return None
    pool = [(k, f["w"]) for k, f in FATES.items() if age >= f["min"] and (f.get("cond") != "目覚め" or st["秘密"]["目覚め"])]
    tot = sum(w for _, w in pool)
    x = rng.random() * tot
    for k, w in pool:
        x -= w
        if x <= 0:
            break
    f = FATES[k]
    add_wound(st, *f["wound"])
    for m, d in f["mood"].items():
        st["気分"][m] = clip(st["気分"][m] + d)
    for n, d in f.get("need", {}).items():
        st["心"][n] = clip(st["心"][n] + d)
    for b, d in f.get("bel", {}).items():
        if b in st["信念"]:
            st["信念"][b]["s"] = clip(st["信念"][b]["s"] + d, -1, 1)
    for fu, d in f["fut"].items():
        st["芽"][fu] = r2(clip(st["芽"].get(fu, 0) + d))
    st["季"]["出来事"].append(f"対話しきれない出来事：{k}")
    log(f"対話しきれない出来事：{FATE_RATE} 出目 {r2(u)} → {k}（傷：{f['wound'][0]} +{f['wound'][1]}）")
    return k


def power_shape(st, rng, log):
    sc = []
    names = list(POWERS)
    for nm in names:
        s = 0
        for k, w in POWERS[nm].items():
            s += w * (feature(st, k) if not k in LIB else feature(st, "b:" + k))
        sc.append(2.5 * s)
    i, ps, u = softmax_pick(sc, rng)
    log("力のかたち：" + "／".join(f"{n} {r2(p)}" for n, p in zip(names, ps)) + f" 出目 {r2(u)}")
    return names[i]


def pick_finder(st, rng):
    opts = [("ちよ", 2 * st["縁"]["ちよ"] + .1), ("辰", st["縁"]["辰"] + .05), ("綾", .5 * st["縁"]["綾"] + .02),
            ("柏木", .1), ("近所の人", .3), ("黒田", .05 + .5 * st["秘密"]["疑い"])]
    tot = sum(w for _, w in opts)
    u = rng.random() * tot
    for n, w in opts:
        u -= w
        if u <= 0:
            return n
    return opts[-1][0]


def dark_risks(st):
    H, V, M = st["心"], st["価値"], st["気分"]
    a = adol(st)
    age = agef(st["w"])
    forb = st.get("禁じた季", 0)
    W = {k: wd["強さ"] for k, wd in st.get("傷", {}).items()}
    wb = {d: .5 * sum(c * W.get(k, 0) for k, c in m.items()) for d, m in WOUND_DARK.items()}
    return {
        "家出": .0 if age < 12 else a * sig(-4.3 + 6 * (.4 - H["安心"]) + 3 * M["怒り"] + .3 * forb + 2 * (.35 - st["自制力"]) + wb["家出"]),
        "悪い仲間": .0 if age < 11.5 else sig(-4.5 + 3 * (.4 - H["居場所"]) + 3 * (.4 - V["しきたり"]) + 3 * st["縁"]["辰"] * (.5 + a) + 4 * (.35 - st["自制力"]) + wb["悪い仲間"]),
        "過激化": .0 if age < 14 else sig(-5.5 + 4 * (V["公正"] - .6) + 3 * (.4 - H["世界"]) + 2 * M["怒り"] + 3 * st["縁"]["草野"] + wb["過激化"]),
        "心を閉ざす": sig(-5 + 5 * (.3 - H["安心"]) + 5 * (.3 - H["自己価値"]) + wb["心を閉ざす"]),
        "言いなり": .0 if age < 12 else sig(-5 + 6 * (.3 - H["自律"]) + 2 * st["自己"]["定める_権威"] + wb["言いなり"]),
    }


def dark_check(st, rng, log):
    for k, p in dark_risks(st).items():
        state = st["暗"][k]
        if state == 2:
            continue
        if p > .03 and state == 0:
            st["暗"][k] = 1
            log(f"前触れ：{k}（週あたり {r2(p)}）。会話か行動に兆しを出す")
        elif p < .015 and state == 1:
            st["暗"][k] = 0
            log(f"前触れが消えた：{k}")
        if state >= 1 and p > .03:
            pw = (p - .03) * .5
            u = rng.random()
            if u < pw:
                st["暗"][k] = 2
                st["季"]["出来事"].append(f"暗い分岐：{k}")
                log(f"暗い分岐：{k} … {r2(pw)} 出目 {r2(u)} → 起きた")


def roll_event(st, rng):
    w = st["w"]
    age = agef(w)
    if w in SPINE:
        plant(st, EVENT_FUT.get(SPINE[w][0], []), .15)
        return ("節目",) + SPINE[w]
    slots = set(st["予定"])
    recent = st.setdefault("最近の出来事", [])
    pool = []
    for (eid, nm, heavy, amin, amax, where, wt, think) in EVENTS:
        if not (amin <= age < amax + 1):
            continue
        places = where.split("|")
        on = "*" in places or bool(slots & set(places))
        if not on or eid in recent or (think and eid in st.setdefault("考えた", [])):
            continue
        pool.append((eid, nm, heavy, wt, think))
    daily = [e for e in pool if not e[4]]
    think = [e for e in pool if e[4]]
    out = ()
    u = rng.random()
    if think and u < .12:
        tot = sum(e[3] for e in think)
        x = rng.random() * tot
        for e in think:
            x -= e[3]
            if x <= 0:
                out = ("考えどころ", e[0], e[1], e[2])
                break
    if not out and daily:
        tot = sum(e[3] for e in daily)
        x = rng.random() * tot
        for e in daily:
            x -= e[3]
            if x <= 0:
                out = ("日常", e[0], e[1], e[2])
                break
    if out and out[0] == "考えどころ":
        st.setdefault("考えた", []).append(out[1])
        del st["考えた"][:-12]   # 考えどころは半年ほど繰り返さない（季に1〜2なので12個でおよそ一年半）
    if out:
        plant(st, EVENT_FUT.get(out[1], []), HEAVY_AMT[out[3]])
        recent.append(out[1])
        del recent[:-6]   # 同じ出来事は6週は繰り返さない
    else:
        out = ("日常", "静か", "とくに何もない週（GMが、その週の予定から小さな日常を一つ描く）", "軽")
    if rng.random() < .025:
        out = out + ("＋町の大事件（嵐・火事・難破・祭りの喧嘩などGMが選ぶ）",)
    return out


def birthday(st, rng, log):
    T = st["気質"]
    H = st["心"]
    T["敏感"] = r2(clip(T["敏感"] + .04 * ((1 - H["安心"]) - T["敏感"])))
    T["自制"] = r2(clip(T["自制"] + .08 * (st["自制力"] - T["自制"])))
    T["情"] = r2(clip(T["情"] + .04 * (st["価値"]["思いやり"] - T["情"])))
    log(f"誕生日：気質が少し動いた（敏感 {T['敏感']}・自制 {T['自制']}・情 {T['情']}）")


def attach_style(st):
    A = st["愛着"]
    H = st["心"]
    if H["安心"] >= .55 and A["応え"] >= .5:
        return "安定"
    if A["応え"] < .35:
        return "回避"
    if A["一貫"] < .45:
        return "不安"
    return "形づくり中"


def identity(st):
    S = st["自己"]
    if agef(st["w"]) < 12.5:
        return "まだ"
    k = max(S["定める"], S["定める_権威"])
    if S["探る"] >= .45 and S["定める"] >= .4:
        return "達成"
    if k >= .4 and S["探る"] < .45:
        return "早期完了"
    if S["探る"] >= .45:
        return "模索"
    return "拡散"


