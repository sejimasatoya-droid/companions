def softmax_pick(scores, rng, temp=1.0):
    m = max(scores)
    ex = [math.exp((s - m) / temp) for s in scores]
    z = sum(ex)
    ps = [e / z for e in ex]
    u = rng.random()
    acc = 0
    for i, p in enumerate(ps):
        acc += p
        if u < acc:
            return i, ps, u
    return len(ps) - 1, ps, u


