TABLES = {"性格": 性格, "好きなもの": 好き, "嫌いなもの": 嫌い, "突飛": 突飛}


def past():
    t = (DIR / "過去と事情.md").read_text()
    return [m.group(1) for m in re.finditer(r"^\| \d+ \| (.+) \|$", t, re.M)]


def pick(lst, n=1):
    out = []
    for _ in range(n):
        i = random.randrange(len(lst))
        out.append(f"（1d{len(lst)}={i+1}）{lst[i]}")
    return out


def write_tables():
    for name, lst in TABLES.items():
        lines = [f"# {name}の表（1d{len(lst)}）", ""]
        if name == "突飛":
            lines += ["ふつうの人物は、特徴を引いたあと 1d10 を振り、1 が出たら、この表から一つ引く。特別な人物は必ず一つ引く。",
                      "出たものは、世界の側の事情（精霊・霊・闇の結社・陣営）とつなげて理由を考える。合わなければ、近い形に読みかえてよい。", ""]
        lines += ["| 目 | 中身 |", "|---|---|"] + [f"| {i+1} | {x} |" for i, x in enumerate(lst)]
        (DIR / f"{name}.md").write_text("\n".join(lines) + "\n")
    print("書いた：", ", ".join(TABLES))


def main():
    a = sys.argv[1:]
    mode = a[0] if a else "ふつう"
    if mode == "表を書く":
        return write_tables()
    if mode == "突飛":
        print("突飛：", pick(突飛)[0]); return
    print("性格：", " ／ ".join(pick(性格, 2)))
    print("好きなもの：", " ／ ".join(pick(好き, 2)))
    print("嫌いなもの：", " ／ ".join(pick(嫌い, 2)))
    print("過去と事情：", " ／ ".join(pick(past(), 2)))
    roll = random.randint(1, 10)
    if mode == "特別" or roll == 1:
        print(f"突飛{'（特別）' if mode == '特別' else f'（1d10={roll}）'}：", pick(突飛)[0])
    else:
        print(f"突飛：なし（1d10={roll}）")


if __name__ == "__main__":
    main()
